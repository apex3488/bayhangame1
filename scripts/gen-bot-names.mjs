// Generates supabase/functions/_shared/names.ts: Russian names of jobs, items, cases, resources
// and games, taken from the game's own dictionaries so the bot and the app use the same words.
//   node scripts/gen-bot-names.mjs
import fs from "node:fs";

const PREFIXES = ["job_", "realty_", "car_", "business_", "lux_", "case_", "res_", "game_", "err_"];
// Same override order as DICTS.ru in lib/i18n.ts: base, extra, then brand names (ruBrands spreads `brands`).
const sources = [
  ["lib/i18n.ts", "const ru: Dict = {"],
  ["lib/i18n-extra.ts", "export const ruExtra: Dict = {"],
  ["lib/i18n-brands.ts", "const brands: Dict = {"],
  ["lib/i18n-brands.ts", "export const ruBrands: Dict = {"],
  ["lib/i18n-social.ts", "export const ruSocial: Dict = {"],
  ["lib/i18n-telegram.ts", "export const ruTelegram: Dict = {"],
];
const LINE = /^\s+([a-z0-9_]+):\s*"((?:[^"\\]|\\.)*)",?\s*$/gm;
const names = {};
for (const [file, start] of sources) {
  const text = fs.readFileSync(file, "utf8");
  const from = text.indexOf(start);
  if (from < 0) throw new Error(`${start} not found in ${file}`);
  const block = text.slice(from, text.indexOf("\n};", from));
  for (const m of block.matchAll(LINE)) {
    if (PREFIXES.some((p) => m[1].startsWith(p))) names[m[1]] = m[2];
  }
}
const out = `// GENERATED by scripts/gen-bot-names.mjs from lib/i18n*.ts — do not edit by hand.
export const NAMES: Record<string, string> = ${JSON.stringify(names, null, 2)};
`;
fs.writeFileSync("supabase/functions/_shared/names.ts", out);
console.log(`names: ${Object.keys(names).length}`);
